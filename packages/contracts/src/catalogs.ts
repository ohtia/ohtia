function catalog(locale: InterfaceLocale, row: Row) {
  const messages = Object.fromEntries(messageKeys.map((key, i) => [key, row[i]])) as Messages;
  for (const text of Object.values(messages)) {
    // This first surface has no interpolation/plural parameters. Reject accidental template syntax.
    if (!text || /[{}<>]/.test(text)) throw new Error("Invalid locale catalog message.");
  }
  return { version: 1, locale, messages } as const;
}
